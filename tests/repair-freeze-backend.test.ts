async function sha256Text(text: string): Promise<string> {
  return createHash("sha256").update(text, "utf8").digest("hex");
}
function ordinaryChild(owner: SessionManager, workflowId: string, toolCallId: string, label: string) {
  const directory = workflowSessionDirectory(owner.getSessionDir(), workflowId);
  const entryId = owner.appendMessage(fauxAssistantMessage(fauxToolCall("agent_spawn", { title: label, request: "Work", label }, { id: toolCallId })));
  const session = SessionManager.create(owner.getSessionDir(), directory);
  session.appendCustomEntry("agent-coordination.identity", { agentId: session.getSessionId(), workflowId, directSpawnerAgentId: owner.getSessionId(), creationPreset: null, spawnSource: { agentId: owner.getSessionId(), entryId, toolCallId }, metadata: { label } });
  session.appendMessage(fauxAssistantMessage("Persist"));
  return session;
}
test("frozen enumeration excludes repair namespace even while live repairer appends", async () => {
  const root = await mkdtemp(join(tmpdir(), "repair-freeze-enum-"));
  const owner = SessionManager.create(root, root);
  const workflowId = owner.getSessionId();
  owner.appendCustomEntry("agent-coordination.identity", { agentId: owner.getSessionId(), workflowId, directSpawnerAgentId: null, metadata: { label: "Owner", description: "Workflow Owner" } });
  const directory = workflowSessionDirectory(root, workflowId);
  const childA = ordinaryChild(owner, workflowId, "spawn-a", "child-a");
  const childB = ordinaryChild(owner, workflowId, "spawn-b", "child-b");
  const repairDir = repairSessionDirectory(root, workflowId);
  const repair = SessionManager.create(root, repairDir);
  repair.appendCustomEntry("agent-coordination.identity", { agentId: repair.getSessionId(), workflowId, directSpawnerAgentId: null, metadata: { label: "Moderator", description: "Manual repair" } });
  repair.appendMessage(fauxAssistantMessage("Live repairer persists."));
  const repairPath = repair.getSessionFile() as string;
  assert.equal(isRepairManagedPath(repairPath, directory), true);
  let targets = await listFrozenRepairTargets(directory);
  assert.ok(targets.indexOf(repairPath) === -1, "live repair transcript must never be a frozen target");
  assert.ok(targets.indexOf(childA.getSessionFile() as string) !== -1, "original inventory stays a target");
  assert.ok(targets.indexOf(childB.getSessionFile() as string) !== -1, "original inventory stays a target");
  repair.appendMessage(fauxAssistantMessage("Live repairer appends during freeze."));
  targets = await listFrozenRepairTargets(directory);
  assert.ok(targets.every((path) => isRepairManagedPath(path, directory) === false));
  assert.equal(targets.length, 2);
});
