test("inspect/verify are read-only and backup/restore round-trips with hash check", async () => {
  const root = await mkdtemp(join(tmpdir(), "repair-freeze-rw-"));
  const owner = SessionManager.create(root, root);
  const workflowId = owner.getSessionId();
  owner.appendCustomEntry("agent-coordination.identity", { agentId: owner.getSessionId(), workflowId, directSpawnerAgentId: null, metadata: { label: "Owner", description: "Workflow Owner" } });
  const child = ordinaryChild(owner, workflowId, "spawn-rw", "child");
  const targetPath = child.getSessionFile() as string;
  const beforeBytes = await readFile(targetPath, "utf8");
  const beforeHash = await sha256File(targetPath);
  assert.equal(beforeHash, await sha256Text(beforeBytes));
  const inspection = await inspectFrozenCopy(targetPath);
  assert.equal(inspection.sessionPath, targetPath);
  assert.ok(inspection.entryCount >= 1);
  assert.equal(await readFile(targetPath, "utf8"), beforeBytes);
  const verification = await verifyFrozenCopy(targetPath);
  assert.equal(verification.sessionPath, targetPath);
  assert.equal(verification.disposition, "pass");
  assert.equal(await readFile(targetPath, "utf8"), beforeBytes);
  assert.equal(await sha256File(targetPath), beforeHash);
  const backupRoot = await mkdtemp(join(tmpdir(), "repair-freeze-backup-"));
  const backup = await backupFrozenTargets([targetPath], backupRoot);
  assert.ok(backup.backupDir.indexOf(backupRoot) === 0);
  assert.notEqual(backup.backupDir, backupRoot);
  assert.equal(basename(backup.manifestPath), "manifest.json");
  assert.equal(backup.entries.length, 1);
  assert.equal(backup.entries[0] as unknown as { sha256: string }, backup.entries[0]);
  assert.equal((backup.entries[0] as { sha256: string }).sha256, beforeHash);
  assert.equal(await readFile(targetPath, "utf8"), beforeBytes);
  const restoreDir = await mkdtemp(join(tmpdir(), "repair-freeze-restore-"));
  const restored = await restoreFrozenBackup(backup.backupDir, restoreDir);
  assert.equal(restored.entries.length, 1);
  const restoredBytes = await readFile(restored.entries[0].restoredPath, "utf8");
  assert.equal(restoredBytes, beforeBytes);
  assert.equal(await sha256File(restored.entries[0].restoredPath), beforeHash);
  assert.equal(await readFile(targetPath, "utf8"), beforeBytes);
});
test("repair_validate is advisory-only: no edits, no authority, resolve still required", async () => {
  const root = await mkdtemp(join(tmpdir(), "repair-validate-adv-"));
  const owner = SessionManager.create(root, root);
  const workflowId = owner.getSessionId();
  owner.appendCustomEntry("agent-coordination.identity", { agentId: owner.getSessionId(), workflowId, directSpawnerAgentId: null, metadata: { label: "Owner", description: "Workflow Owner" } });
  const child = ordinaryChild(owner, workflowId, "spawn-adv", "child");
  const targetPath = child.getSessionFile() as string;
  const beforeBytes = await readFile(targetPath, "utf8");
  const beforeListing = await readdir(root);
  const report = await validateRepairFreezeAdvisory({ transcriptPaths: [targetPath], stage: "validate" });
  assert.equal(report.advisory, true);
  assert.equal(report.authorizesBytes, false);
  assert.equal(report.sealsNothing, true);
  assert.equal(report.effectsApplied, false);
  assert.equal(report.resolveInvoked, false);
  assert.ok(report.installedSource.packageDir.length > 0);
  assert.equal(await readFile(targetPath, "utf8"), beforeBytes);
  assert.deepEqual(await readdir(root), beforeListing);
  child.appendMessage(fauxAssistantMessage("Late write after advisory."));
  const afterBytes = await readFile(targetPath, "utf8");
  assert.notEqual(afterBytes, beforeBytes);
  const second = await validateRepairFreezeAdvisory({ transcriptPaths: [targetPath], stage: "validate" });
  assert.equal(second.authorizesBytes, false);
  assert.notDeepEqual(second, report);
});
