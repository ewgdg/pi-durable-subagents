function rosterStatus(agentId: string, workflowId: string, phase: string) {
  return { agentId, workflowId, label: agentId === workflowId ? "Owner" : "Moderator", description: agentId === workflowId ? "Workflow Owner" : "Repair Moderator", directSpawnerAgentId: agentId === workflowId ? null : workflowId, primaryEvidence: { transcriptPath: null, inspectedThrough: { agentId, entryId: "tail" } }, run: phase === "live" ? { phase: "live", work: "active", attention: "none", retentionReasons: [] } : { phase: "dormant" }, model: { provider: "steady-provider", modelId: "v1" }, thinking: "off", compacting: false, queuedInputCount: 0 } as never;
}
async function setupRepairedCoordinator(t: any, attemptId: string) {
  let owner: any;
  const host = await createUnboundTestOwnerHost(t, createAgentBoundExtension(() => owner), { persistent: true, processVisibleModel: true, implicitModeratorResponses: false });
  const identity = adoptOrValidateOwnerIdentity(host.runtime);
  const coordinator = new WorkflowCoordinator(host.runtime, identity, { entryModulePath: "<inline:pi-durable-subagents>" });
  t.after(() => coordinator.shutdown(async () => undefined).catch(() => undefined));
  await coordinator.initializePreadmissionRepair();
  owner = coordinator.forAgent(identity.agentId);
  await bindTestOwnerHost(host, "tui");
  const sessionDir = host.session.sessionManager.getSessionDir();
  const workflowDir = workflowSessionDirectory(sessionDir, identity.workflowId);
  const ownerMgr = host.session.sessionManager;
  const toolId = "spawn-hint-" + attemptId;
  const entryId = ownerMgr.appendMessage(fauxAssistantMessage(fauxToolCall("agent_spawn", { title: "hint-child", request: "Work", label: "hint-child" }, { id: toolId })));
  const child = SessionManager.create(ownerMgr.getSessionDir(), workflowDir);
  child.appendCustomEntry("agent-coordination.identity", { agentId: child.getSessionId(), workflowId: identity.workflowId, directSpawnerAgentId: identity.agentId, creationPreset: null, spawnSource: { agentId: identity.agentId, entryId, toolCallId: toolId }, metadata: { label: "hint-child" } });
  child.appendMessage(fauxAssistantMessage("Persist hint-child"));
  host.model.setResponses([() => fauxAssistantMessage("Repair triage holding.")]);
  const receipt = await owner.requestManualRepair("hint refresh triage " + attemptId);
  assert.equal(receipt.disposition, "created");
  const snapshot = await owner.freezeRepairSnapshot();
  assert.ok(snapshot.entries.length >= 1);
  const scratch = await mkdtemp(join(tmpdir(), "repair-hint-" + attemptId + "-"));
  const repairedBySource: Record<string, string> = {};
  for (const entry of snapshot.entries) {
    const rp = join(scratch, basename(entry.source) + ".repaired.jsonl");
    await copyFile(entry.source, rp);
    SessionManager.open(rp).appendMessage(fauxAssistantMessage("Repaired note."));
    repairedBySource[entry.source] = rp;
  }
  const result = await owner.commitRepairReplace(repairedBySource, "attempt-hint-" + attemptId);
  assert.ok(result.disposition === "committed" || result.disposition === "joined-committed");
  return { host, identity, coordinator, owner, receipt };
}
test("pre-admission snapshot shows pending with no live Owner (filtered repair scope)", async () => {
  const moderatorId = "moderator-hint-1";
  const ownerId = "owner-hint-1";
  const repaired = buildRepairedOwnerEntry({ ownerId, workflowId: ownerId, transcriptPath: "/tmp/repaired-owner.jsonl", stage: "admission-pending" });
  const fakeView: any = { status: () => ({ agentId: moderatorId }), selectionRoster: () => ({ live: [rosterStatus(moderatorId, ownerId, "live")], dormant: [] }), humanAttention: () => [], operationalAttention: () => [], reportHistory: () => [], repairedOwnerEntry: () => repaired };
  const snap = createAgentSelectorSnapshot(fakeView, moderatorId);
  assert.equal(snap.live.length, 1);
  assert.equal(snap.dormant.length, 0);
  assert.ok((snap as any).repairedOwner);
  assert.equal((snap as any).repairedOwner.stage, "admission-pending");
  assert.equal((snap as any).repairedOwner.ownerId, ownerId);
  assert.ok(![...snap.live, ...snap.dormant].some((s: any) => s.agentId === s.workflowId));
});
test("post-admission snapshot of SAME coordinator shows live Owner and zero pending (staleness regression)", async (t) => {
  const { host, identity, coordinator, owner } = await setupRepairedCoordinator(t, "refresh-a");
  const preEntry = owner.repairedOwnerEntry();
  assert.ok(preEntry);
  assert.equal(preEntry.stage, "admission-pending");
  const preSnap = createAgentSelectorSnapshot(owner, owner.status().agentId);
  assert.ok((preSnap as any).repairedOwner);
  assert.equal((preSnap as any).repairedOwner.stage, "admission-pending");
  const admitted = await owner.admitRepairedOwner();
  assert.equal(admitted.ownerId, identity.agentId);
  assert.equal(admitted.snapshot.agentId, identity.agentId);
  const postEntry = owner.repairedOwnerEntry();
  assert.equal(postEntry, undefined);
  const postSnap = createAgentSelectorSnapshot(owner, owner.status().agentId);
  const liveOwner = [...postSnap.live, ...postSnap.dormant].find((s: any) => s.agentId === s.workflowId);
  assert.ok(liveOwner, "expected live Owner roster item post-admission");
  assert.equal(liveOwner.agentId, identity.agentId);
  assert.equal((postSnap as any).repairedOwner, undefined);
  await assert.rejects(owner.beginExecution(), /idle_until_human_message/);
  await owner.resumeFromHuman("human takes over after repair", undefined);
  await owner.beginExecution();
  await coordinator.shutdown(async () => host.runtime.dispose());
});
test("reopening selector after admit reflects live state (no snapshot cache)", async (t) => {
  const { host, identity, coordinator, owner } = await setupRepairedCoordinator(t, "refresh-b");
  const admitted = await owner.admitRepairedOwner();
  assert.equal(admitted.ownerId, identity.agentId);
  const reopened = createAgentSelectorSnapshot(owner, owner.status().agentId);
  assert.ok([...reopened.live, ...reopened.dormant].some((s: any) => s.agentId === identity.agentId && s.agentId === s.workflowId));
  assert.equal((reopened as any).repairedOwner, undefined);
  const handlers = createOwnerAgentPresentationHandlers(() => owner, owner.status().agentId);
  const viaHandlers = await handlers.snapshot();
  assert.ok([...viaHandlers.live, ...viaHandlers.dormant].some((s: any) => s.agentId === identity.agentId && s.agentId === s.workflowId));
  assert.equal((viaHandlers as any).repairedOwner, undefined);
  await coordinator.shutdown(async () => host.runtime.dispose());
});
