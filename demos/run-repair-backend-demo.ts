import { mkdtemp } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { SessionManager } from "@earendil-works/pi-coding-agent";
import { fauxAssistantMessage, fauxToolCall } from "@earendil-works/pi-ai";
import { repairSessionDirectory } from "../src/coordination/manual-repair.ts";
import { backupFrozenTargets, inspectFrozenBackup, inspectFrozenCopy, listFrozenRepairTargets, sha256File, verifyFrozenCopy } from "../src/coordination/repair-freeze.ts";
import { describeInstalledRepairSource, validateRepairFreezeAdvisory } from "../src/coordination/repair-validate.ts";
import { workflowSessionDirectory } from "../src/runtime/workflow-session-directory.ts";

const root = await mkdtemp(join(tmpdir(), "repair-demo-"));
const owner = SessionManager.create(root, root);
const workflowId = owner.getSessionId();
owner.appendCustomEntry("agent-coordination.identity", { agentId: workflowId, workflowId, directSpawnerAgentId: null, metadata: { label: "Owner" } });
const dir = workflowSessionDirectory(root, workflowId);
const entryId = owner.appendMessage(fauxAssistantMessage(fauxToolCall("agent_spawn", { title: "child-a", request: "Work", label: "child-a" }, { id: "spawn-a" })));
const child = SessionManager.create(owner.getSessionDir(), dir);
child.appendCustomEntry("agent-coordination.identity", { agentId: child.getSessionId(), workflowId, directSpawnerAgentId: workflowId, creationPreset: null, spawnSource: { agentId: workflowId, entryId, toolCallId: "spawn-a" }, metadata: { label: "child-a" } });
child.appendMessage(fauxAssistantMessage("Persist"));
const repairDir = repairSessionDirectory(root, workflowId);
const repair = SessionManager.create(root, repairDir);
repair.appendCustomEntry("agent-coordination.identity", { agentId: repair.getSessionId(), workflowId, directSpawnerAgentId: null, metadata: { label: "Moderator" } });
repair.appendMessage(fauxAssistantMessage("live append"));
const targets = await listFrozenRepairTargets(dir);
console.log("frozen targets (repair excluded):", targets.length, targets.map((t) => t.split("/").pop()));
const before = await sha256File(child.getSessionFile() as string);
const insp = await inspectFrozenCopy(child.getSessionFile() as string);
const ver = await verifyFrozenCopy(child.getSessionFile() as string);
console.log("inspect entries:", insp.entryCount, "verify:", ver.disposition, ver.warnings.slice(0, 2));
console.log("read-only:", (await sha256File(child.getSessionFile() as string)) === before ? "yes" : "NO - MUTATED");
const backup = await backupFrozenTargets(targets, root + "-backups");
console.log("backup:", backup.backupDir.split("/").pop(), "entries:", backup.entries.length);
const restored = await inspectFrozenBackup(backup.backupDir, root + "-restore");
console.log("restore files:", restored.entries.length);
const adv = await validateRepairFreezeAdvisory({ transcriptPaths: targets, stage: "demo" });
console.log("advisory: authorizesBytes=", adv.authorizesBytes, " sealsNothing=", adv.sealsNothing, " entries=", adv.files[0]?.entryCount);
console.log("root:", root);
